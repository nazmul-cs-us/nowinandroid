def kotlin_string(value: str) -> str:
    escaped = (
        value.replace("\\", "\\\\")
        .replace("\"", "\\\"")
        .replace("$", "\\$")
        .replace("\n", "\\n")
        .replace("\r", "")
        .replace("\t", " ")
    )
    # Collapse the multi-space runs the source JSON uses for isnad pauses.
    escaped = " ".join(escaped.split())
    return f'"{escaped}"'


def squish(value: str) -> str:
    return " ".join((value or "").split())


class Book:
    def __init__(self, id_, name_en, name_ar, first, last, count):
        self.id = id_
        self.name_en = name_en
        self.name_ar = name_ar
        self.first = first
        self.last = last
        self.count = count


def compute_books(data: dict) -> list[Book]:
    hadiths = data.get("hadiths", [])
    chapters = {c.get("id"): c for c in data.get("chapters", [])}
    meta_arabic = (data.get("metadata", {}).get("arabic", {}) or {}).get("title", "")

    ranges = OrderedDict()
    for position, hadith in enumerate(hadiths, start=1):
        chapter_id = hadith.get("chapterId")
        key = chapter_id if chapter_id is not None else "__null__"
        entry = ranges.setdefault(key, [position, position, 0])
        entry[1] = position
        entry[2] += 1

    books: list[Book] = []
    null_chapter = chapters.get(None)
    next_synthetic_id = max((k for k in ranges if isinstance(k, int)), default=0) + 1
    for key, (first, last, count) in ranges.items():
        if key == "__null__":
            chapter = null_chapter or {}
            book_id = next_synthetic_id
            next_synthetic_id += 1
            name_en = squish(chapter.get("english") or "Appendix")
            name_ar = squish(chapter.get("arabic") or meta_arabic)
        else:
            chapter = chapters.get(key, {})
            book_id = int(key)
            name_en = squish(chapter.get("english") or f"Book {key}")
            name_ar = squish(chapter.get("arabic") or meta_arabic)
        books.append(Book(book_id, name_en, name_ar, first, last, count))

    # Sanity: contiguous coverage of 1..N with no overlaps.
    for previous, current in zip(books, books[1:]):
        if previous.last + 1 != current.first:
            raise ValueError(
                f"Non-contiguous range between {previous.name_en} (…{previous.last}) "
                f"and {current.name_en} ({current.first}…)"
            )
    if books and (books[0].first != 1 or books[-1].last != len(hadiths)):
        raise ValueError("Book ranges do not span 1..hadith count")
    return books


def emit_books_object(object_name: str, source_file: str, db_name: str, books: list[Book]) -> str:
    lines = [
        HEADER,
        f"package {REGISTRY_PACKAGE}",
        "",
        "/**",
        f" * The canonical books and their exact ranges in `{db_name}`.",
        " *",
        f" * Generated by scripts/generate_hadith_collection_models.py from",
        f" * AhmedBaset/hadith-json v1.2.0 ({source_file}); the database rows are",
        " * created from the same source in the same order, so these ranges line",
        " * up 1:1 with the database ids.",
        " */",
        f"object {object_name} {{",
        "    val all: List<HadithCollectionBookEntry> = listOf(",
    ]
    for book in books:
        lines.append(
            "        HadithCollectionBookEntry("
            f"{book.id}, {kotlin_string(book.name_en)}, {kotlin_string(book.name_ar)}, "
            f"{book.first}, {book.last}, {book.count}"
            "),"
        )
    lines.append("    )")
    lines.append("}")
    return "\n".join(lines) + "\n"


def verify_against_db(books: list[Book], data: dict, db_path: Path) -> None:
    hadiths = data.get("hadiths", [])
    if not db_path.exists():
        print(f"    db not found locally, skipped verification: {db_path.name}")
        return
    connection = sqlite3.connect(db_path)
    db_count = connection.execute("SELECT COUNT(*) FROM hadiths").fetchone()[0]
    connection.close()
    if db_count != len(hadiths):
        raise ValueError(f"DB count {db_count} != JSON count {len(hadiths)} for {db_path.name}")
    covered = sum(book.count for book in books)
    if covered != db_count:
        raise ValueError(f"Book counts sum to {covered}, DB has {db_count}")
    print(f"    verified against {db_path.name}: {db_count} hadiths, {len(books)} books")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--json-dir", required=True, help="Directory with the downloaded book JSONs")
    parser.add_argument("--db-dir", default="", help="Directory with the built collection .db files (verification)")
    parser.add_argument("--output", required=True, help="Kotlin output directory (core/model .../data)")
    args = parser.parse_args()

    json_dir = Path(args.json_dir)
    db_dir = Path(args.db_dir) if args.db_dir else None
    output = Path(args.output)
    output.mkdir(parents=True, exist_ok=True)

    plan = [
        # (json file, Kotlin object, db file)
        ("muslim.json", "MuslimBooks", "sahih_muslim.db"),
        ("nasai.json", "NasaiBooks", "sunan_nasai.db"),
        ("tirmidhi.json", "TirmidhiBooks", "sunan_tirmidhi.db"),
        ("abudawud.json", "AbuDawudBooks", "sunan_abu_dawud.db"),
        ("ibnmajah.json", "IbnMajahBooks", "sunan_ibn_majah.db"),
        ("malik.json", "MalikBooks", "muwatta_malik.db"),
        # Crawl-merged sources (scripts/fetch_tohed_collection.py +
        # tohed_jsonl_to_hadith_json.py); skipped when the JSON is absent.
        ("darimi.json", "DarimiBooks", "sunan_darimi.db"),
        ("ahmad.json", "AhmadBooks", "musnad_ahmad.db"),
    ]
    for json_file, object_name, db_file in plan:
        json_path = json_dir / json_file
        if not json_path.exists():
            print(f"{json_file} not present, skipped ({object_name})")
            continue
        print(f"{json_file} -> {object_name}")
        data = json.loads((json_dir / json_file).read_text())
        books = compute_books(data)
        db_path = (db_dir / db_file) if db_dir else None
        if db_path:
            verify_against_db(books, data, db_path)
        text = emit_books_object(object_name, json_file, db_file, books)
        (output / f"{object_name}.kt").write_text(text, encoding="utf-8")
        print(f"    wrote {object_name}.kt ({len(books)} books)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

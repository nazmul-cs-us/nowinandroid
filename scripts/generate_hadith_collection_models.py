#!/usr/bin/env python3
"""Generate Kotlin hadith-collection book models from AhmedBaset/hadith-json.

The collection databases are created from the same JSON sources by
scripts/create_hadith_collection_db.py (rows = enumerate(hadiths, 1)), so each
hadith's chapterId maps exactly to its DB row id. This script recomputes every
chapter's contiguous id range and emits one Kotlin file per collection with a
`<Name>Books` object, mirroring the hand-written BukhariBooks/ShamayelBooks
pattern, plus the HadithCollections registry.

Sources are pinned to tag v1.2.0:
  https://raw.githubusercontent.com/AhmedBaset/hadith-json/v1.2.0/
      db/by_book/the_9_books/<book>.json

Usage:
  python3 scripts/generate_hadith_collection_models.py --json-dir /tmp/hadith-json \
      --db-dir /tmp/hadith-dbs --output core/model/src/commonMain/kotlin/.../data
"""

